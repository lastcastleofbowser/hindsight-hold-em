/// <reference types="vitest" />
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import { createHash } from 'node:crypto';

/**
 * Generates `sw.js` at build time with a precache list of every emitted file,
 * so the whole app works offline after the first visit. No runtime dependency
 * on Workbox — the worker is ~40 lines and easy to audit.
 */
function offlineServiceWorker(): Plugin {
  return {
    name: 'hindsight-offline-sw',
    apply: 'build',
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map'));
      const precache = ['./', './index.html', './manifest.webmanifest', './icon.svg', ...files.map((f) => `./${f}`)];
      const version = createHash('sha1').update(precache.join('|')).digest('hex').slice(0, 10);
      const source = `// Generated by vite.config.ts — do not edit.
const CACHE = 'hindsight-${version}';
const PRECACHE = ${JSON.stringify([...new Set(precache)])};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('hindsight-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  const url = new URL(req.url);
  // Never cache the account/history API: it must always be live.
  if (req.method !== 'GET' || url.origin !== self.location.origin || url.pathname.includes('/api/')) return;
  if (req.mode === 'navigate') {
    // Network first for the page so updates arrive, cached shell when offline.
    event.respondWith(fetch(req).catch(() => caches.match('./index.html')));
    return;
  }
  event.respondWith(
    caches.match(req).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) caches.open(CACHE).then((c) => c.put(req, res.clone()));
      return res;
    }))
  );
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}

// Friends (/ws) and accounts (/api) are served by the game server (npm run server).
const friendsProxy = {
  '/ws': { target: 'ws://localhost:8787', ws: true },
  '/api': { target: 'http://localhost:8787' },
};

export default defineConfig({
  base: './',
  plugins: [react(), offlineServiceWorker()],
  server: { proxy: friendsProxy },
  preview: { proxy: friendsProxy },
  test: {
    environment: 'node',
    include: ['src/**/*.test.ts', 'server/**/*.test.ts'],
  },
});
